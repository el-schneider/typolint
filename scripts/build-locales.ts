// Writes src/locales.generated.ts from Unicode CLDR quotation delimiters.
// Usage: pnpm locales [locale ...]   (no arguments: the default set below)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const defaultLocales = [
  "en",
  "en-GB",
  "de",
  "fr",
  "es",
  "it",
  "nl",
  "pl",
  "cs",
  "sv",
  "da",
  "fi",
  "pt",
  "tr",
];
const locales = process.argv.length > 2 ? process.argv.slice(2) : defaultLocales;

const require = createRequire(import.meta.url);
const cldrRoot = dirname(require.resolve("cldr-misc-full/package.json"));
const cldrVersion: string = JSON.parse(readFileSync(join(cldrRoot, "package.json"), "utf8")).version;

interface Delimiters {
  quotationStart: string;
  quotationEnd: string;
  alternateQuotationStart: string;
  alternateQuotationEnd: string;
}

const pair = (open: string, close: string) => `[${JSON.stringify(open)}, ${JSON.stringify(close)}]`;

const rows = locales.map((locale) => {
  const json = JSON.parse(readFileSync(join(cldrRoot, "main", locale, "delimiters.json"), "utf8"));
  const d: Delimiters = json.main[locale].delimiters;
  const primary = pair(d.quotationStart, d.quotationEnd);
  const secondary = pair(d.alternateQuotationStart, d.alternateQuotationEnd);
  return `  ${JSON.stringify(locale)}: { primary: ${primary}, secondary: ${secondary} },`;
});

const out = `// Generated by scripts/build-locales.ts from cldr-misc-full ${cldrVersion}. Do not edit; run \`pnpm locales\`.
import type { QuotePairs } from "./locale.ts";

export const cldrVersion: string = ${JSON.stringify(cldrVersion)};

export const cldrQuotes: Readonly<Record<string, QuotePairs>> = {
${rows.join("\n")}
};
`;

writeFileSync(new URL("../src/locales.generated.ts", import.meta.url), out);
console.log(`wrote ${locales.length} locales from CLDR ${cldrVersion}`);
